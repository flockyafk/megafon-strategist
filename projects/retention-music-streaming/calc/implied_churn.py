# Условный расчёт: средний месячный отток, подразумеваемый удержанием на 3-м месяце (E1).
# Допущение: отток постоянен по месяцам (на деле он обычно выше в 1-й месяц после триала).
for r in (0.60, 0.50):
    m = 1 - r ** (1 / 3)
    print(f"retention_m3={r:.2f} -> implied monthly churn={m:.3f}, lost in 3 months={1-r:.2f}")
print(f"relative growth of 3-month loss: {(0.50/0.40-1):.0%}")
