print("=== Мощность пилота (приближённо, 80% мощность, 5% значимость) ===")
from math import sqrt
for base in (0.02, 0.03, 0.05):
    for n in (2000, 5000, 10000):
        se = sqrt(2 * base * (1 - base) / n)
        print(f"базовая доля подключений за период {base:.0%}, группа {n}: минимально различимый прирост ~{2.8*se*100:.1f} п.п.")
c_se = sqrt(2 * 0.015 * 0.985 / 10000)
