print("=== A'. Пересчёт на реальную цену 199 руб. с бесплатным первым месяцем (E25) ===")
price = 199
for share in (0.10, 0.20, 0.30):
    for c in (0.05, 0.10, 0.15):
        paid = months_paid(c) - 1.0  # первый месяц бесплатный
        cac = share * price * paid
        print(f"комиссия {int(share*100)}%, отток {int(c*100)}%/мес: допустимый CAC за 12 мес. ~{cac:.0f} руб.")
print("(без НДС, платёжных комиссий, поддержки; конверсия триала в платный не учтена: допустимый CAC на ПОДКЛЮЧЕНИЕ ещё ниже)")

