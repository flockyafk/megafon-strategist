"""Порядок величин экономики двух вариантов. Все входы [допущение]: внутренних данных нет.
Запуск: python projects/megafon-demo/calc/unit_economics.py
"""

def months_paid(churn, horizon=12):
    """Ожидаемое число оплаченных месяцев за горизонт при месячном оттоке churn."""
    return sum((1 - churn) ** t for t in range(horizon))

print("=== A. Отдельная продажа (оператор получает комиссию от цены партнёра) ===")
print("Макс. допустимая стоимость привлечения (CAC), руб., чтобы окупиться за 12 мес.")
print("цена | комиссия | отток 5%/мес | 10% | 15%")
for price in (199, 299, 449):
    for share in (0.10, 0.20, 0.30):
        row = [share * price * months_paid(c) for c in (0.05, 0.10, 0.15)]
        print(f"{price} | {int(share*100)}% | " + " | ".join(f"{x:.0f}" for x in row))

print()
print("=== B. Встроить в тариф ===")
print("Стоимость для оператора = оптовая цена W за каждого абонента тарифа в месяц (платит и за неиспользующих).")
print("Окупаемость: W <= (доп. ARPU) + (маржа абонента) * (снижение оттока в мес.) * (мес. горизонта)... упрощённо:")
print("Нужное снижение месячного оттока тарифа, чтобы покрыть W при марже m и базовом оттоке c0 (горизонт 12 мес.)")
m = 150  # [допущение] маржа с абонента тарифа, руб./мес
c0 = 0.015  # [допущение] базовый месячный отток абонентов оператора ~1,5%
print(f"m={m} руб., c0={c0:.1%}")
max_gain = m * (months_paid(0.0) - months_paid(c0))
print(f"Максимальная выгода от удержания за 12 мес. на абонента, даже если отток упадёт до нуля: {max_gain:.0f} руб.")
for W in (30, 60, 100, 150):
    print(f"W={W} руб./мес: затраты за 12 мес. {W*12} руб. на абонента; "
          f"{'покрываются' if max_gain >= W*12 else 'НЕ покрываются'} одним удержанием, нужен доп. ARPU (рост цены тарифа/апсейл)")

print()
